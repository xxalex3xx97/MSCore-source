-- underground belt: 01 00 + i32 Length (cells, entrance..exit inclusive). mk = 1|2|3 checks M.UG_MAX (optional).
M.UG_MAX = { [1] = 8, [2] = 10, [3] = 12 }
function M.encode_ug(len, mk)
    if math.type(len) ~= "integer" or len < 1 then return nil, "length must be an integer >= 1" end
    local max = mk and M.UG_MAX[mk]
    if max and len > max then return nil, "length " .. len .. " over Mk" .. mk .. " max " .. max end
    return string.pack("<I2", 1) .. string.pack("<i4", len)
end

-- "01 00 0f 00" -> byte string, spaces ignored
function M.cfg_hex(hex)
    local s = (hex:gsub("%s+", ""))
    if #s % 2 ~= 0 or s:find("[^%x]") then return nil, "not hex" end
    return (s:gsub("%x%x", function(p) return string.char(tonumber(p, 16)) end))
end

function M.to_hex(b)
    local t = {}
    for i = 1, #b do t[i] = string.format("%02x", b:byte(i)) end
    return table.concat(t, " ")
end

---------------------------------------------------------------- game reads (in game only)
local function valid(o)
    if o == nil or type(o) ~= "userdata" then return false end
    local ok, v = pcall(function() return o:IsValid() end)
    return ok and v == true
end

-- every Recipe object: {name = asset FName, obj = object}. crafter/inputs/outputs not read (fields UNK).
function M.recipes()
    local out = {}
    local ok, all = pcall(FindAllOf, "Recipe")
    if not ok or not all then return out end
    for _, o in ipairs(all) do
        if valid(o) then
            local okn, n = pcall(function() return o:GetFName():ToString() end)
            if okn and n then out[#out + 1] = { name = n, obj = o } end
        end
    end
    return out
end

function M.recipe_by_name(name)
    for _, r in ipairs(M.recipes()) do
        if r.name == name then return r end
    end
    return nil
end

function M.install(MSCore) MSCore.factory = M; return M end

return M
