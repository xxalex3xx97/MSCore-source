-- rot: any integer, odd = quarter turn (w and h swap)
function M.footprint(dat, rot)
    local t = M.tables[dat]
    if not t then return nil, "unknown machine dat " .. tostring(dat) end
    if (rot or 0) % 2 == 1 then return t.h, t.w end
    return t.w, t.h
end

-- layer of a height (floor division by 8, as the probe's pp_layer)
function M.layer(h) return (h or 0) // 8 end

-- blocks: list of {class=, gx=, gy=, h=, rot=} (h, rot optional). Floor centre = gx*8, gy*8; half extents from tbl
-- (swapped on odd rot). Blocks without a floor are left out. Returns {x=, y=, w=, h=, layer=} (w,h = half extents).
function M.floor_rects(blocks, tbl)
    tbl = tbl or M.block_floor
    local out = {}
    for _, b in ipairs(blocks) do
        local t = tbl[b.class]
        if t and not t.nofloor and t.w > 0 and t.h > 0 then
            local hw, hh = t.w, t.h
            if (b.rot or 0) % 2 == 1 then hw, hh = hh, hw end
            out[#out + 1] = { x = b.gx * 8, y = b.gy * 8, w = hw, h = hh, layer = M.layer(b.h) }
        end
    end
    return out
end

-- floors: list from floor_rects. existing: machine records {dat,x,y,h,rot}. m: {dat,x,y,h,rot}.
-- Rules (probe pp_check_new): parity (x-w and y-h even); inside one floor of the same layer (DAT_SignWall exempt);
-- no overlap with an existing machine of the same layer. Returns true, or false + reason.
function M.validate_place(floors, existing, m)
    local w, h = M.footprint(m.dat, m.rot)
    if not w then return false, "unknown machine dat " .. tostring(m.dat) end
    if (m.x - w) % 2 ~= 0 or (m.y - h) % 2 ~= 0 then
        return false, "parity (x must match w, y must match h): " .. m.dat
    end
    local layer = M.layer(m.h)
    if m.dat ~= "DAT_SignWall" then
        local inside = false
        for _, f in ipairs(floors) do
            if f.layer == layer and m.x - w >= f.x - f.w and m.x + w <= f.x + f.w
                and m.y - h >= f.y - f.h and m.y + h <= f.y + f.h then
                inside = true
                break
            end
        end
        if not inside then return false, "outside every floor of its layer: " .. m.dat end
    end
    for _, e in ipairs(existing) do
        if M.layer(e.h) == layer then
            local ew, eh = M.footprint(e.dat, e.rot)
            if not ew then return false, "unknown footprint of existing " .. tostring(e.dat) end
            if m.x - w < e.x + ew and e.x - ew < m.x + w and m.y - h < e.y + eh and e.y - eh < m.y + h then
                return false, "overlap with " .. e.dat .. " at (" .. e.x .. "," .. e.y .. ")"
            end
        end
    end
    return true, ""
end

---------------------------------------------------------------- config bytes (rea-machine-config.md, little endian)
-- FString: int32 length incl NUL, then bytes, then NUL. Empty / nil = int32 0.
local function fstring(s)
    if s == nil or s == "" then return string.pack("<i4", 0) end
    return string.pack("<i4", #s + 1) .. s .. "\0"
end

-- ports: booleans or numbers (0 = off). int32 n, then n bytes 0/1.
local function port_bytes(ports)
    local t = {}
    for i, v in ipairs(ports or {}) do
        local on = v == true or (type(v) == "number" and v ~= 0)
        t[i] = string.char(on and 1 or 0)
    end
    return string.pack("<i4", #t) .. table.concat(t)
end

-- recipe machines (assembler, refinery, enrichment, ...): 01 00 + FString recipe + i32 n + n port bytes
function M.encode_cfg(c)
    return string.pack("<I2", 1) .. fstring(c.recipe) .. port_bytes(c.ports)
end

local function rd_fstring(b, pos)
    local n
    n, pos = string.unpack("<i4", b, pos)
    if n == 0 then return "", pos end
    if n < 0 then error("utf-16 fstring not supported") end
    if pos + n - 1 > #b then error("fstring past end") end
    if b:byte(pos + n - 1) ~= 0 then error("fstring not NUL terminated") end
    return b:sub(pos, pos + n - 2), pos + n
end

-- returns {recipe=, ports={bool...}} or nil, err (wrong version, bad strings, trailing bytes)
function M.decode_cfg(b)
    local ok, res = pcall(function()
        local ver, pos = string.unpack("<I2", b, 1)
        if ver ~= 1 then error("config version " .. ver) end
        local recipe
        recipe, pos = rd_fstring(b, pos)
        local n
        n, pos = string.unpack("<i4", b, pos)
        if n < 0 or pos + n - 1 > #b then error("port count past end") end
        local ports = {}
        for i = 1, n do ports[i] = b:byte(pos + i - 1) ~= 0 end
        pos = pos + n
        if pos <= #b then error("trailing bytes") end
        return { recipe = recipe, ports = ports }
    end)
    if ok then return res end
    return nil, tostring(res)
end

-- splitter / balancer: 01 00, i32 n, n x FString filter, i32 prio_a, i32 prio_b (-1 = default), i32 n, n port bytes
function M.encode_splitter(c)
    local f = {}
    for i, s in ipairs(c.filters or {}) do f[i] = fstring(s) end
    return string.pack("<I2", 1) .. string.pack("<i4", #f) .. table.concat(f)
        .. string.pack("<i4i4", c.prio_a or -1, c.prio_b or -1) .. port_bytes(c.ports)
end
